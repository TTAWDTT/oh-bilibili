//! B 站接口适配层。
//!
//! 设计约束：这一层只跟 HTTP 和签名打交道，不碰数据库、不碰播放器状态。
//! 接口一旦变化，改动局限在这个 crate 内。
//!
//! 计划中的模块：
//! - `wbi`    签名所需的 key 管理与参数签名
//! - `client` 带 cookie jar、限速、重试的 HTTP 客户端
//! - `auth`   二维码登录与登录态
//! - `search` 搜索与结果清洗
//! - `video`  视频详情，拿 cid / aid / 时长 / 分区
//! - `play`   取流，DASH 音轨选择
//! - `sync`   收藏夹与点赞
