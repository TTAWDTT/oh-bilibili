import { writeFile } from 'node:fs/promises'
import { createServer } from 'node:http'
import { join } from 'node:path'

export async function checkSocialPages(page, web, wait, check) {
  const buttons = (scope, label) => `[...document.querySelectorAll(${JSON.stringify(scope + ' button')})]
    .find(b => b.getClientRects().length && (b.getAttribute('aria-label') || b.textContent.trim()) === ${JSON.stringify(label)})`
  const element = selector => `document.querySelector(${JSON.stringify(selector)})`
  const click = async expr => {
    await wait(expr)
    await page.evaluate(`(${expr}).click()`)
  }
  const byName = (scope, text) => click(buttons(scope, text))
  const newPage = async query => {
    await page.evaluate(`location.href = ${JSON.stringify(web + '?' + query)}`)
    await wait(`location.search === ${JSON.stringify('?' + query)} && document.querySelector('[data-home-recommend]')`)
  }
  const openSpace = () => click(element('[data-track-card] button[aria-label^="UP "]'))
  const field = element('textarea[aria-label$="发私信"]')
  const log = element('[role="log"]')
  const note = '这是一条预览环境里的私信。'
  const fill = async (value) => {
    await wait(field)
    await page.evaluate(`(() => {
      const input = ${field}
      Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, ${JSON.stringify(value)})
      input.dispatchEvent(new Event('input', { bubbles: true }))
    })()`)
  }

  await page.viewport(1320, 900)
  await newPage('loggedIn=1&failDirectSendOnce=1&directMedia=1')
  await byName('nav[aria-label="主导航"]', '消息')
  await byName('nav[aria-label="消息分类"]', '私信')
  await click(element('[data-direct-peer="5000"]'))
  await wait(field)
  const selectImage = () => page.evaluate(`(() => {
    const files = new DataTransfer()
    const png = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jf/0AAAAASUVORK5CYII='), c => c.charCodeAt(0))
    files.items.add(new File([png], '示例.png', {type:'image/png'}))
    const input = document.querySelector('.dm-compose input[type=file]')
    input.files = files.files
    input.dispatchEvent(new Event('change', {bubbles:true}))
  })()`)
  await fill('你好呀')
  await page.evaluate(`${field}.setSelectionRange(1, 2)`)
  await byName('body', '选择表情')
  await byName('.dm-emotes', '[doge]')
  await wait(`${field}.value === '你[doge]呀'`)
  await selectImage()
  await wait(element('img[alt="待发送图片"]'))
  await click(element('[data-direct-peer="5002"]'))
  await wait(`!${element('img[alt="待发送图片"]')} && ${field}.value === ''`)
  await click(element('[data-direct-peer="5000"]'))
  await wait(element('img[alt="待发送图片"]'))
  await byName('body', '移除图片')
  check('图片和文字草稿跟随各自联系人，移除图片保留文字', await page.evaluate(`${field}.value === '你[doge]呀' && !${element('img[alt="待发送图片"]')}`))
  await selectImage()
  await byName('body', '发送图片')
  await wait(element('.dm-compose [role=alert]'))
  check('发送图片失败后保留附件供重试', await page.evaluate(`!!${element('img[alt="待发送图片"]')}`))
  await byName('body', '发送图片')
  await wait(`!${element('img[alt="待发送图片"]')} && ${log}.querySelector('[data-mine=true] img.dm-image[src^="data:image/png"]')`)
  await byName('body', '发送')
  await wait(`${log}.querySelector('[data-mine=true] img[alt="[doge]"]')`)
  check('图片成功后可单独发送原文字，气泡显示选中的表情', true)
  await newPage('loggedIn=1&directMedia=1')
  await byName('nav[aria-label="主导航"]', '消息')
  await byName('nav[aria-label="消息分类"]', '私信')
  await click(element('[data-direct-peer="5000"]'))
  await wait(`${log}?.querySelector('[data-direct-card] img')`)
  await click(element('[data-direct-card]'))
  await wait(`!document.querySelector('[role=log]') && document.querySelector('button[aria-label="返回"]')`)
  check('私信分享卡的封面和标题可见，点视频进入站内观看', true)
  await newPage('loggedIn=1&directRecall=1')
  await byName('nav[aria-label="主导航"]', '消息')
  await byName('nav[aria-label="消息分类"]', '私信')
  await click(element('[data-direct-peer="5000"]'))
  await wait(`${log}?.querySelector('.dm-image')`)
  const badge = element('nav[aria-label="消息分类"] button[aria-label="私信"]')
  await wait(`${badge}.textContent.includes('2')`)
  await byName('body', '刷新私信')
  await wait(`!${badge}.textContent.includes('2')`)
  check('已读写入失败后刷新同一页可以重试', true)
  await byName('body', '刷新私信')
  await wait(`!${log}.querySelector('.dm-image')`)
  await byName('body', '更早的消息')
  await wait(`${log}.textContent.includes('消息已撤回')`)
  check('跨页撤回会清除图片且后续补页不会恢复原文', await page.evaluate(`!${log}.textContent.includes('看到你发的片段啦') && !${log}.querySelector('.dm-image')`))
  await newPage('loggedIn=1&failDirectSendOnce=1')
  await byName('nav[aria-label="主导航"]', '消息')
  await byName('nav[aria-label="消息分类"]', '私信')
  const first = element('[data-direct-peer="5000"]')
  const other = element('[data-direct-peer="5002"]')
  const tab = element('nav[aria-label="消息分类"] button[aria-label="私信"]')
  await wait(first)
  check('首次进入私信只列联系人，不打开对话', !(await page.evaluate(field)))
  await wait(`${tab}.textContent.includes('2') && document.querySelector('button[aria-label="消息，12 条未读"]')`)
  await byName('body', '更多联系人')
  await wait(element('[data-direct-peer="5003"]'))
  check('翻到下一页联系人后仍保留原列表和未读数', await page.evaluate(`!!${first} && ${tab}.textContent.includes('2')`))
  await click(first)
  const messages = 'document.querySelectorAll("[role=log] [data-direct-message]")'
  await wait(`${messages}.length > 0`)
  await wait(`!${tab}.textContent.includes('2') && document.querySelector('button[aria-label="消息，10 条未读"]')`)
  check('选中会话后，分类和顶栏同步扣除其未读数', true)
  const recent = await page.evaluate(`Array.from(${messages}, m => m.dataset.directMessage)`)
  await byName('body', '更早的消息')
  await wait(`${messages}.length > ${recent.length}`)
  const older = await page.evaluate(`Array.from(${messages}, m => m.dataset.directMessage)`)
  check('向前翻阅保留最近的私信，消息不重复', recent.every(id => older.includes(id)) && new Set(older).size === older.length)

  await fill('   ')
  check('空白私信不能发送', await page.evaluate(`(${buttons('body', '发送')}).disabled`))
  await fill(note)
  await byName('body', '发送')
  await wait(element('[role="alert"]'))
  check('发送失败保留输入，消息记录中不会先出现一条成功记录',
    await page.evaluate(`${field}.value === ${JSON.stringify(note)} && !${log}.innerText.includes(${JSON.stringify(note)})`))
  await byName('body', '发送')
  await wait(`${field}.value === '' && ${log}.innerText.includes(${JSON.stringify(note)})`)
  check('重试成功后只有一条本人的私信', await page.evaluate(`Array.from(${messages}).filter(m =>
    m.dataset.senderMid === '1960976249' && m.textContent.includes(${JSON.stringify(note)})).length === 1`))
  if (process.env.SOCIAL_OUTPUT) {
    const screenshot = await page.cdp('Page.captureScreenshot', { format: 'png' })
    await writeFile(join(process.env.SOCIAL_OUTPUT, '私信预览（演示数据）.png'), Buffer.from(screenshot.result.data, 'base64'))
  }

  await fill('留给第一位联系人的草稿')
  await click(other)
  await wait(`${log}?.getAttribute('aria-label')?.includes('不睡觉的鹿') && ${messages}.length`)
  check('切换联系人后不显示上一人的发言', await page.evaluate(`!${log}.textContent.includes(${JSON.stringify(note)})`))
  await fill('第二位联系人的草稿')
  await click(first)
  await wait(`${field}?.value === '留给第一位联系人的草稿'`)
  await click(other)
  await wait(`${field}?.value === '第二位联系人的草稿'`)
  check('切换联系人后各自的草稿保留在原对话', true)
  await page.viewport(390, 844)
  await byName('body', '返回联系人')
  await wait(`${first}?.getClientRects().length`)
  check('窄窗能够返回联系人列表', await page.evaluate(`document.documentElement.scrollWidth <= innerWidth && !${field}?.getClientRects().length`))

  await page.viewport(1320, 900)
  await click(other)
  await wait(`${messages}.length > 0 && Array.from(${log}.querySelectorAll('img')).every(img => img.complete)`)
  await page.evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
  await byName('body', '账号菜单')
  await byName('body', '退出登录')
  await wait(`!${field} && !${first} && !${log}`)
  check('退出账号后联系人、聊天记录和输入框一起收起', true)
  await newPage('loggedIn=1&spaceShowcase=1&failSpaceProfileOnce=1')
  await openSpace()
  await wait(element('[data-space-banner]'))
  const firstCard = element('#scroll-main [data-track-card]')
  const pinned = element('#scroll-main [data-track-card][data-space-pinned]')
  await wait(`${pinned}?.innerText.includes('置顶投稿')`)
  const pinKey = await page.evaluate(`${pinned}.dataset.key`)
  const pinTitle = await page.evaluate(`${pinned}.dataset.trackTitle`)
  const pinOnlyOnce = `${firstCard} === ${pinned} && ${pinned}?.dataset.key === ${JSON.stringify(pinKey)} && Array.from(document.querySelectorAll('#scroll-main [data-track-card]'))
    .filter(card => card.dataset.key === ${JSON.stringify(pinKey)}).length === 1`
  await wait("document.querySelectorAll('#scroll-main [data-track-card]').length > 1")
  check('作者的置顶在网格第一格，投稿列表没有重复收录', await page.evaluate(pinOnlyOnce))
  await byName('#scroll-main', '最多收藏')
  await wait(`(${buttons('#scroll-main', '最多收藏')}).getAttribute('aria-pressed') === 'true'`)
  check('切换投稿排序后首格仍是同一个置顶视频', await page.evaluate(pinOnlyOnce))
  await click(`${pinned}.querySelector('button[aria-label^=观看]')`)
  await wait(`document.querySelector('.watch-head h1')?.textContent === ${JSON.stringify(pinTitle)}`)
  await click(element('button[aria-label="返回"]'))
  await wait(pinOnlyOnce)
  check('点开置顶能看对应视频，返回后仍在同一空间', true)
  const banner = element('[data-space-banner]')
  await wait(`${banner}.currentSrc.endsWith('precious-editing-desk.webp') && ${banner}.naturalWidth > 0`)
  const notice = element('[data-space-notice]')
  const room = element('[aria-label="打开直播间：剪辑室"]')
  await wait(`${notice}?.getClientRects().length && ${room}?.getClientRects().length`)
  check('宽窗投稿在左、公告与直播间在右，作者佩戴的标识可见', await page.evaluate(`
    ${notice}.getBoundingClientRect().left >= ${firstCard}.parentElement.getBoundingClientRect().right &&
    ${room}.getBoundingClientRect().left >= ${firstCard}.parentElement.getBoundingClientRect().right &&
    !!document.querySelector('[alt="箱庭少女之梦头像"]') && !!document.querySelector('[alt="十年大会员"]') &&
    !!document.querySelector('[title="见习偶像"]')`))
  await byName('#scroll-main', '空间资料')
  await wait(buttons('#scroll-main', '重新加载空间资料'))
  check('扩展资料取不到时仍可看公告、置顶投稿及 B 站空间', await page.evaluate(`!!${pinned} && !!${notice} && !!(${buttons('#scroll-main', '去 B 站空间查看勋章')})`))
  await byName('#scroll-main', '粉丝勋章墙')
  await wait(`document.querySelector('ul[aria-label="粉丝勋章"]')?.textContent.includes('同行 18')`)
  check('整面勋章墙可以单独查看，扩展资料失败也能打开', true)
  await byName('#scroll-main', '重新加载空间资料')
  await wait(buttons('#scroll-main', '充电'))
  check('资料重试成功后显示公开生日、充电和已佩戴粉丝牌', await page.evaluate(`document.querySelector('section[aria-label="空间资料"]').textContent.includes('05-16') &&
    document.querySelector('[title="佩戴的粉丝勋章"]').textContent.includes('剪辑 18')`))
  const uid = await page.evaluate("document.querySelector('header[data-up-mid]').dataset.upMid")
  await byName('nav[aria-label="空间内容"]', '动态')
  await wait(`document.querySelector('section[aria-label="作者动态"]') && !${notice}?.getClientRects().length`)
  await byName('nav[aria-label="空间内容"]', '投稿')
  await wait(`${pinned}?.getClientRects().length`)
  check('看过动态再回到投稿，刚展开的资料和勋章墙仍在', await page.evaluate(`
    (${buttons('#scroll-main', '空间资料')})?.getAttribute('aria-expanded') === 'true' &&
    document.querySelector('section[aria-label="空间资料"]')?.innerText.includes(${JSON.stringify(uid)}) &&
    document.querySelector('ul[aria-label="粉丝勋章"]')?.innerText.includes('同行 18')`))
  await page.viewport(390, 844)
  await wait(`${banner}.currentSrc.endsWith('cover-fallback.jpg') && ${banner}.naturalWidth > 0`)
  check('窄窗展开资料可以读公告、看直播间，且没有横向溢出', await page.evaluate(`
    ${notice}.getClientRects().length && ${room}.getClientRects().length && document.documentElement.scrollWidth <= innerWidth`))
  await byName('#scroll-main', '空间资料')
  await page.evaluate("document.getElementById('scroll-main').scrollTop = 0")
  check('窄窗收起资料后，首屏能看到置顶封面和标题', await page.evaluate(`
    !${notice}?.getClientRects().length && !${room}?.getClientRects().length &&
    ${pinned}.getBoundingClientRect().top >= document.getElementById('scroll-main').getBoundingClientRect().top &&
    ${pinned}.querySelector('h3').getBoundingClientRect().bottom <= document.getElementById('scroll-main').getBoundingClientRect().bottom`))
  await page.viewport(1320, 900)
  await wait(`${notice}?.getClientRects().length && ${room}?.getClientRects().length`)
  const missing = createServer((_, res) => { res.writeHead(404); res.end() })
  await new Promise(resolve => missing.listen(0, '127.0.0.1', resolve))
  try {
    const absent = JSON.stringify(`http://127.0.0.1:${missing.address().port}/missing-banner.webp`)
    await page.evaluate(`${banner}.src = ${absent}`)
    await wait(`${banner}?.currentSrc.endsWith('cover-fallback.jpg') && ${banner}.naturalWidth > 0`)
    check('宽窗大图返回 404 后继续显示有效的小头图', true)
    await newPage('loggedIn=1&spaceShowcase=1')
    await page.viewport(390, 844)
    await openSpace()
    await wait(`${banner}?.currentSrc.endsWith('cover-fallback.jpg') && ${banner}.naturalWidth > 0`)
    await page.evaluate(`${banner}.previousElementSibling.srcset = ${absent}`)
    await wait(`${banner}?.currentSrc.endsWith('precious-editing-desk.webp') && ${banner}.naturalWidth > 0`)
    check('窄窗小图返回 404 后继续显示有效的大头图', true)
    await page.viewport(1320, 900)
  } finally { missing.close() }
  await byName('#scroll-main', '代表作')
  await wait(element('[data-track-card]'))
  check('代表作可从空间内容栏单独查看', await page.evaluate(`(${buttons('#scroll-main', '代表作')}).getAttribute('aria-pressed') === 'true'`))
  await byName('#scroll-main', '合集和系列')
  await click(element('[data-space-collection]'))
  const work = element('[data-collection-work]')
  await wait(work)
  const title = await page.evaluate(`${work}.getAttribute('aria-label')`)
  await click(work)
  await wait(`document.querySelector('button[aria-label="返回"]') && !${work}`)
  await click(element('button[aria-label="返回"]'))
  await wait(`${work}?.getAttribute('aria-label') === ${JSON.stringify(title)}`)
  check('点开合集作品后返回同一目录', true)

  const dynamics = 'section[aria-label="作者动态"]'
  await byName('nav[aria-label="空间内容"]', '动态')
  await wait(element(dynamics + ' [data-dynamic-id] img[alt="[doge]"]'))
  check('作者空间的置顶动态、正文表情和投票卡一起出现', await page.evaluate(`(() => {
    const entry = document.querySelector(${JSON.stringify(dynamics + ' [data-dynamic-id]')})
    return entry.textContent.includes('置顶') && entry.querySelector('a[href*="vote_id"]')?.textContent.includes('下一期想看什么')
  })()`))
  check('作者行展示站方装扮、保留编号前导零，并能打开对应装扮', await page.evaluate(`(() => {
    const card = document.querySelector(${JSON.stringify(dynamics + ' a[href*="item_id=1685952496002"]')})
    return card?.textContent.includes('000102') && card.querySelector('img')?.alt === '2233夏日摇滚派对粉丝'
  })()`))
  const filter = element(dynamics + ' input[type="search"]')
  await page.evaluate(`(() => {
    const input = ${filter}
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '晴天')
    input.dispatchEvent(new Event('input', { bubbles: true }))
  })()`)
  await wait(`!${element(dynamics + ' [data-dynamic-id]')}`)
  await byName(dynamics, '更多动态')
  await wait(`${element(dynamics + ' [data-dynamic-id]')}?.textContent.includes('晴天')`)
  check('空间动态搜索也能找到随后翻页加载的内容', true)
  await click(element(dynamics + ' [data-dynamic-open="video"]'))
  await click(element('button[aria-label="返回"]'))
  await wait(`${filter}?.value === '晴天' && ${element(dynamics + ' [data-dynamic-id]')}?.textContent.includes('晴天')`)
  check('从后续动态里的视频返回，搜索词和所在页得到恢复', true)
  await newPage('spaceDynamicsBlocked=1')
  await openSpace()
  await byName('nav[aria-label="空间内容"]', '动态')
  await wait(buttons(dynamics, '重试'))
  check('受限时保留当前作者官网动态入口', await page.evaluate(`(() => {
    const author = document.querySelector('[data-up-mid]').dataset.upMid
    return document.querySelector(${JSON.stringify(dynamics + ' a')})?.href === 'https://space.bilibili.com/' + author + '/dynamic'
  })()`))

  await newPage('loggedIn=1&spaceShowcase=1')
  await byName('body', '账号菜单')
  await byName('body', '个人空间')
  await byName('#scroll-main', '空间资料')
  await wait(`document.querySelector('section[aria-label="空间资料"]').textContent.includes('生日')`)
  check('自己的空间显示公开资料，收起给自己发消息、充电和关注的动作', await page.evaluate(`
    document.querySelector('section[aria-label="空间资料"]').textContent.includes('1960976249') &&
    !(${buttons('#scroll-main', '充电')}) && !(${buttons('#scroll-main', '发消息')}) && !(${buttons('#scroll-main', '关注')})`))
  await newPage('loggedIn=1&spaceEmpty=1')
  await openSpace()
  await wait(buttons('#scroll-main', '发消息'))
  const author = await page.evaluate("document.querySelector('#scroll-main h2')?.textContent.trim()")
  await wait("document.getElementById('scroll-main')?.innerText.includes('这个 UP 主还没有公开投稿')")
  check('没有投稿的账号仍显示资料和发消息入口', !!author && !await page.evaluate(firstCard))
  await byName('#scroll-main', '发消息')
  await wait(`${field}?.getAttribute('aria-label')?.includes(${JSON.stringify(author)})`)
  check('从个人空间发消息直接进入该用户的站内对话', true)
}
